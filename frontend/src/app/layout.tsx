import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { connection } from "next/server";
import { headers } from "next/headers";
import { ThemeProvider } from "@/components/theme-provider";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: {
    default: "OpenSlate Operations",
    template: "%s | OpenSlate",
  },
  description: "A focused workspace for departments, modules, and records.",
};

const themeInitScript = `try{var s=localStorage.getItem("openslate-theme");var t=s==="dark"||s==="light"?s:"light";var e=document.documentElement;e.classList.toggle("dark",t==="dark");e.dataset.accent=localStorage.getItem("openslate-accent")??"cobalt";e.dataset.density=localStorage.getItem("openslate-density")??"comfortable";e.dataset.radius=localStorage.getItem("openslate-radius")??"subtle"}catch(e){}`;

export default async function RootLayout({ children }: LayoutProps<"/">) {
  // A per-request render lets Next.js apply the CSP nonce generated by proxy.ts
  // to framework scripts and styles.
  await connection();
  const nonce = (await headers()).get("x-nonce") ?? undefined;
  return (
    <html
      lang="en"
      // The blocking theme script above mutates <html> (dark class +
      // data-* attributes) before hydration, so the DOM intentionally
      // differs from this render. Suppress the warning and keep React
      // from patching those attributes back.
      suppressHydrationWarning
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <head>
        <script
          nonce={nonce}
          dangerouslySetInnerHTML={{ __html: themeInitScript }}
        />
      </head>
      <body className="flex min-h-full flex-col">
        <ThemeProvider />
        {children}
      </body>
    </html>
  );
}
