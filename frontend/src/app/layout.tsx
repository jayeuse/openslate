import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { connection } from "next/server";
import { ThemeProvider } from "@/components/theme-provider";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: {
    default: "OpenSlate Operations",
    template: "%s | OpenSlate",
  },
  description: "A focused workspace for departments, modules, and records.",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
  // A per-request render lets Next.js apply the CSP nonce generated by proxy.ts
  // to framework scripts and styles.
  await connection();
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="flex min-h-full flex-col">
        <ThemeProvider />
        {children}
      </body>
    </html>
  );
}
